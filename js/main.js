/* ===========================================================
   TAM SAYFA BÖLÜM KAYDIRMA (FULL-PAGE SECTION SCROLL)
   Sadece masaüstünde çalışır; FP_MIN_WIDTH altındaki
   genişliklerde (mobil/tablet) tamamen devre dışı kalır,
   sayfa normal, serbest kayan haliyle çalışmaya devam eder.
   =========================================================== */
(function () {
  // ---- AYARLANABİLİR DEĞİŞKENLER ----
  const FP_MIN_WIDTH = 1025;          // bu genişliğin altında efekt tamamen kapalı
  const FP_DURATION_MS = 680;         // bölümler arası geçiş süresi
  const FP_EASING = 'cubic-bezier(.4,0,.2,1)'; // geçiş easing'i
  const FP_WHEEL_DEBOUNCE_MS = 900;   // bir geçişten sonra yeni wheel'in kaç ms sonra kabul edileceği
  const FP_WHEEL_THRESHOLD = 35;      // trackpad'lerdeki ufak titreşimleri yok saymak için eşik
  const FP_TOUCH_THRESHOLD = 60;      // dokunmatik ekranlarda (masaüstü) kaydırma eşiği

  const root = document.documentElement;
  const wrapper = document.getElementById('fpWrapper');
  const dotsNav = document.getElementById('fpDots');
  if (!wrapper || !dotsNav) return; // sayfa yapisi yoksa sessizce cik

  const sections = Array.from(wrapper.querySelectorAll('[data-fp-section]'));
  const dots = Array.from(dotsNav.querySelectorAll('.fp-dot'));
  const total = sections.length;
  const mainHeader = document.getElementById('mainHeader');

  let currentIndex = 0;
  let isAnimating = false;
  let fpActive = false;
  let touchStartY = null;

  const mq = window.matchMedia(`(min-width: ${FP_MIN_WIDTH}px)`);

  function applyLightClass(index) {
    const isLight = sections[index] && sections[index].dataset.fpLight === 'true';
    root.classList.toggle('fp-on-light', isLight);
    // Header, tam sayfa kaydirma modunda artik gercek scrollY hareket etmedigi
    // icin eski scroll dinleyicisi tetiklenmiyor; ayni "scrolled" gorunumunu
    // (beyaz zemin + koyu yazi) burada, aktif section'a gore biz tetikliyoruz.
    // "force-light-header" isaretli sayfalarda (ör. hakkimizda, bulgular)
    // section'in koyu/acik olmasindan bagimsiz olarak header hep beyaz kalir.
    // "data-fp-header-light" ise TEK BIR section icin (ör. koyu zeminli ama
    // header'i yine de beyaz gorunmesi istenen ticaret agi section'i) ayni
    // seyi yapar; ancak noktalarin (fp-dots) rengini etkilemez.
    const forceLight = document.body.classList.contains('force-light-header');
    const sectionHeaderLight = sections[index] && sections[index].dataset.fpHeaderLight === 'true';
    if (mainHeader && fpActive) {
      mainHeader.classList.toggle('scrolled', isLight || forceLight || sectionHeaderLight);
    }
  }

  function updateDots(index) {
    dots.forEach((d, i) => {
      const active = i === index;
      d.classList.toggle('active', active);
      d.setAttribute('aria-current', active ? 'true' : 'false');
    });
  }

  function goToSection(index) {
    if (!fpActive) return;
    const goingForward = index > currentIndex;
    index = Math.max(0, Math.min(total - 1, index));
    if (index === currentIndex || isAnimating) return;
    isAnimating = true;
    currentIndex = index;
    // Sabit "index * 100vh" varsayımı yerine, hedef section'ın wrapper içindeki
    // gerçek konumunu kullanıyoruz. Böylece bir section (ör. çok sayıda bulgu
    // kartı içeren "Bulgular") bir ekrandan uzun olsa bile diğer section'lar
    // kaymıyor, hiçbir içerik görünmez alanda kesilip kaybolmuyor.
    const targetTop = sections[index].offsetTop;
    updateDots(index);
    applyLightClass(index);
    // ÖNEMLİ: tam sayfa kaydırma modunda gerçek scroll olmadığı (sadece
    // transform ile atlama yapıldığı) için, IntersectionObserver tabanlı
    // ".reveal" görünürlük efekti bazı section'larda hiç tetiklenmeyip
    // içeriğin (basliklar, kartlar) opacity:0'da sonsuza dek kalmasına
    // sebep olabiliyordu. Section'a fiilen girildiğinde, o section
    // içindeki tüm reveal elementlerini burada DOĞRUDAN aktif ediyoruz,
    // observer'a güvenmeden; bu, içeriğin görünmez kalma riskini tamamen
    // ortadan kaldırıyor.
    if (sections[index]) {
      sections[index].querySelectorAll('.reveal').forEach(el => el.classList.add('active'));
    }
    // Hedef section'a ileri yönde giriliyorsa en üstünden, geri yönde
    // giriliyorsa en altından baslasin (dogal, beklenen kaydirma hissi icin)
    subScroll = goingForward ? 0 : sectionOverflow(index);
    wrapper.style.transform = `translateY(-${targetTop + subScroll}px)`;
    window.setTimeout(() => { isAnimating = false; }, FP_DURATION_MS);
  }

  let subScroll = 0; // aktif section icinde (kendi tasan kismi icinde) ne kadar asagi kayildigi

  function sectionOverflow(index) {
    const sec = sections[index];
    if (!sec) return 0;
    return Math.max(0, sec.offsetHeight - window.innerHeight);
  }

  function applySubScroll(animated) {
    const base = sections[currentIndex].offsetTop;
    wrapper.style.transition = animated ? '' : 'none';
    wrapper.style.transform = `translateY(-${base + subScroll}px)`;
    if (!animated) {
      // bir sonraki frame'de tekrar normal gecis suresine don
      requestAnimationFrame(() => { wrapper.style.transition = ''; });
    }
  }

  function onWheel(e) {
    if (!fpActive) return;
    // Footer artik tam sayfa kaydirma sisteminin DISINDA, normal bir block.
    // Sayfa footer bolgesine (scrollY > 0) kaymissa, wheel'i hic ele almiyoruz,
    // tarayicinin kendi normal scroll'u calissin.
    if (window.scrollY > 0) return;
    if (Math.abs(e.deltaY) < FP_WHEEL_THRESHOLD) return;

    // Son section'dayken ve o section'in da tasan kismi bittiyse, asagi
    // kaydirmaya devam edilirse artik "bir sonraki section" yok; kontrolu
    // tarayicinin normal scroll'una birakiyoruz ki footer'a inilebilsin.
    const overflowNow = sectionOverflow(currentIndex);
    if (e.deltaY > 0 && currentIndex === total - 1 && subScroll >= overflowNow) {
      return; // preventDefault YOK: native scroll footer'i acar
    }

    e.preventDefault();
    if (isAnimating) return;

    // Aktif section tek ekrandan (viewport) uzun olabilir (ör. çok satırlı
    // künye). Böyle durumlarda önce o fazlalık kısmı kendi içinde "sub-scroll"
    // ile gösteriyoruz; section'ın sonuna/basina ulasilinca barbir sonraki/
    // önceki section'a normal sekilde geciyoruz.
    const overflow = sectionOverflow(currentIndex);
    if (e.deltaY > 0) {
      if (subScroll < overflow) {
        subScroll = Math.min(overflow, subScroll + e.deltaY);
        applySubScroll(false);
        return;
      }
      goToSection(currentIndex + 1);
    } else {
      if (subScroll > 0) {
        subScroll = Math.max(0, subScroll + e.deltaY);
        applySubScroll(false);
        return;
      }
      goToSection(currentIndex - 1);
    }
  }

  function isTypingTarget(el) {
    if (!el) return false;
    const tag = el.tagName ? el.tagName.toLowerCase() : '';
    return tag === 'input' || tag === 'textarea' || tag === 'select' || el.isContentEditable;
  }

  function onKeydown(e) {
    if (!fpActive) return;
    if (window.scrollY > 0) return; // footer bolgesindeyiz, klavye de normal scroll yapsin
    if (isTypingTarget(document.activeElement)) return; // arama kutusu vb. yazarken engelleme
    if (e.key === 'ArrowDown' || e.key === 'PageDown') {
      const overflowNow = sectionOverflow(currentIndex);
      if (currentIndex === total - 1 && subScroll >= overflowNow) return; // native scroll'a birak
      e.preventDefault();
      goToSection(currentIndex + 1);
    } else if (e.key === 'ArrowUp' || e.key === 'PageUp') {
      e.preventDefault();
      goToSection(currentIndex - 1);
    }
  }

  function onTouchStart(e) {
    if (!fpActive) return;
    touchStartY = e.touches[0].clientY;
  }
  function onTouchEnd(e) {
    if (!fpActive || touchStartY === null) return;
    const deltaY = touchStartY - e.changedTouches[0].clientY;
    touchStartY = null;
    if (Math.abs(deltaY) < FP_TOUCH_THRESHOLD) return;
    goToSection(currentIndex + (deltaY > 0 ? 1 : -1));
  }

  function onDotClick(e) {
    const idx = parseInt(e.currentTarget.getAttribute('data-fp-index'), 10);
    goToSection(idx);
  }

  function enableFullPage() {
    if (fpActive) return;
    fpActive = true;
    root.classList.add('fp-mode');
    root.style.setProperty('--fp-duration', FP_DURATION_MS + 'ms');
    root.style.setProperty('--fp-easing', FP_EASING);
    currentIndex = 0;
    wrapper.style.transform = 'translateY(0)';
    updateDots(0);
    applyLightClass(0);
    if (sections[0]) {
      sections[0].querySelectorAll('.reveal').forEach(el => el.classList.add('active'));
    }
    window.addEventListener('wheel', onWheel, { passive: false });
    window.addEventListener('keydown', onKeydown);
    window.addEventListener('touchstart', onTouchStart, { passive: true });
    window.addEventListener('touchend', onTouchEnd, { passive: true });
  }

  function disableFullPage() {
    if (!fpActive) return;
    fpActive = false;
    root.classList.remove('fp-mode', 'fp-on-light');
    wrapper.style.transform = '';
    window.removeEventListener('wheel', onWheel, { passive: false });
    window.removeEventListener('keydown', onKeydown);
    window.removeEventListener('touchstart', onTouchStart, { passive: true });
    window.removeEventListener('touchend', onTouchEnd, { passive: true });
  }

  function syncWithViewport() {
    if (mq.matches) enableFullPage();
    else disableFullPage();
  }

  dots.forEach(d => d.addEventListener('click', onDotClick));
  mq.addEventListener ? mq.addEventListener('change', syncWithViewport) : mq.addListener(syncWithViewport);
  window.addEventListener('resize', () => {
    // sadece breakpoint gercekten degistiyse tepki ver (gereksiz sik tetiklenmeyi onler)
    syncWithViewport();
  });

  syncWithViewport();
})();

